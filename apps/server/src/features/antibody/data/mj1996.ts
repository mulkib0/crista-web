const read = (tri: readonly (readonly number[])[], a: string, b: string): number | null => {
  const i = MJ_INDEX[a];
  const j = MJ_INDEX[b];
  if (i === undefined || j === undefined) return null;
  const row = i >= j ? tri[i] : tri[j];
  const col = i >= j ? j : i;
  return row?.[col] ?? null;
};

